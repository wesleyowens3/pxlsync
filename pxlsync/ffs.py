"""Drive FreeFileSync in batch mode.

pxlsync writes a ``.ffs_batch`` file and runs the installed FreeFileSync with
it. FreeFileSync itself is unmodified and installed separately, so pxlsync's
own code is not affected by FreeFileSync's GPL license.

If the studio has a batch file saved from its own FreeFileSync version (with
preferred comparison, deletion and error settings), point pxlsync at it as a
template: pxlsync only replaces the folder pair and the exclude filter.
"""

from __future__ import annotations

import os
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

MODES = {
    # label: (LeftOnly, LeftNewer, RightNewer, RightOnly) actions
    "Mirror  (dest becomes exact copy)": ("right", "right", "right", "right"),
    "Update  (copy new/changed, never delete)": ("right", "right", "none", "none"),
}

EXIT_CODES = {
    0: "Sync finished",
    1: "Sync finished with warnings",
    2: "Sync finished with errors",
    3: "Sync was cancelled",
}

DEFAULT_EXCLUDES = [
    "\\System Volume Information\\",
    "\\$Recycle.Bin\\",
    "\\RECYCLE?\\",
    "\\.Trash-*\\",
    "*\\.DS_Store",
    "*\\Thumbs.db",
    "*\\desktop.ini",
    "*\\.pxlsync-tmp-*",
]


def find_freefilesync() -> str | None:
    if env := os.environ.get("PXLSYNC_FFS"):
        return env if Path(env).exists() else None
    if sys.platform == "win32":
        candidates = [
            Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "FreeFileSync" / "FreeFileSync.exe",
            Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "FreeFileSync" / "FreeFileSync.exe",
        ]
    elif sys.platform == "darwin":
        candidates = [
            Path("/Applications/FreeFileSync.app/Contents/MacOS/FreeFileSync"),
            Path.home() / "Applications/FreeFileSync.app/Contents/MacOS/FreeFileSync",
        ]
    else:
        candidates = [Path("/opt/FreeFileSync/FreeFileSync"), Path("/usr/bin/FreeFileSync")]
    for c in candidates:
        if c.exists():
            return str(c)
    return shutil.which("FreeFileSync")


def filter_item(root: Path, file: Path, sep: str = os.sep) -> str:
    """FreeFileSync filter entry for one file, relative to the synced folder."""
    rel = file.relative_to(root)
    return sep + sep.join(rel.parts)


def _default_tree() -> ET.ElementTree:
    root = ET.Element("FreeFileSync", XmlType="BATCH", XmlFormat="17")
    ET.SubElement(root, "Notes").text = "Generated by pxlsync"
    cmp = ET.SubElement(root, "Compare")
    ET.SubElement(cmp, "Variant").text = "TimeAndSize"
    ET.SubElement(cmp, "Symlinks").text = "Exclude"
    ET.SubElement(cmp, "IgnoreTimeShift")
    sync = ET.SubElement(root, "Synchronize")
    ET.SubElement(sync, "Differences")
    ET.SubElement(sync, "DeletionPolicy").text = "RecycleBin"
    ET.SubElement(sync, "VersioningFolder", Style="Replace")
    flt = ET.SubElement(root, "Filter")
    ET.SubElement(ET.SubElement(flt, "Include"), "Item").text = "*"
    ET.SubElement(flt, "Exclude")
    ET.SubElement(flt, "SizeMin", Unit="None").text = "0"
    ET.SubElement(flt, "SizeMax", Unit="None").text = "0"
    ET.SubElement(flt, "TimeSpan", Type="None").text = "0"
    ET.SubElement(root, "FolderPairs")
    ET.SubElement(root, "Errors", Ignore="false", Retry="0", Delay="5")
    ET.SubElement(root, "PostSyncCommand", Condition="Completion")
    ET.SubElement(root, "LogFolder")
    batch = ET.SubElement(root, "Batch")
    ET.SubElement(batch, "ProgressDialog", Minimized="false", AutoClose="false")
    ET.SubElement(batch, "ErrorDialog").text = "Show"
    ET.SubElement(batch, "PostSyncAction").text = "None"
    return ET.ElementTree(root)


def build_batch(
    source: Path,
    dest: Path,
    mode: str,
    exclude_files: list[Path] | None = None,
    template: Path | None = None,
    sep: str = os.sep,
) -> str:
    tree = ET.parse(template) if template else _default_tree()
    root = tree.getroot()
    if root.tag != "FreeFileSync":
        raise ValueError("template is not a FreeFileSync configuration file")
    root.set("XmlType", "BATCH")

    pairs = root.find("FolderPairs")
    if pairs is None:
        pairs = ET.SubElement(root, "FolderPairs")
    for child in list(pairs):
        pairs.remove(child)
    pair = ET.SubElement(pairs, "Pair")
    ET.SubElement(pair, "Left").text = str(source)
    ET.SubElement(pair, "Right").text = str(dest)

    if not template:  # keep a template's own sync direction settings
        diff = root.find("Synchronize/Differences")
        left_only, left_newer, right_newer, right_only = MODES[mode]
        diff.attrib.update(LeftOnly=left_only, LeftNewer=left_newer, RightNewer=right_newer, RightOnly=right_only)

    flt = root.find("Filter")
    if flt is None:
        flt = ET.SubElement(root, "Filter")
    excl = flt.find("Exclude")
    if excl is None:
        excl = ET.SubElement(flt, "Exclude")
    existing = {i.text for i in excl.findall("Item")}
    defaults = [d.replace("\\", sep) for d in DEFAULT_EXCLUDES]
    for item in defaults + [filter_item(source, f, sep) for f in exclude_files or []]:
        if item not in existing:
            ET.SubElement(excl, "Item").text = item
            existing.add(item)

    ET.indent(tree, space="    ")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"
